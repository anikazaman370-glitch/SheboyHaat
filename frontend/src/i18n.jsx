export function toBanglaDigits(value) {
  return String(value).replace(/[0-9]/g, (d) => banglaDigits[Number(d)]);
}

export function localizeNumber(lang, value) {
  return lang === "বাংলা" ? toBanglaDigits(value) : String(value);
}

